    private static byte[] Layout(int count = 1, int type = 45)
    {
        var bytes = new byte[56 + count * 64];
        "LGB1"u8.CopyTo(bytes); "LGP1"u8.CopyTo(bytes.AsSpan(12));
        Write(bytes, 4, bytes.Length); Write(bytes, 8, 1); Write(bytes, 32, 1); Write(bytes, 36, 4);
        Write(bytes, 48, 16); Write(bytes, 52, count);
        for (var i = 0; i < count; i++)
        {
            Write(bytes, 56 + i * 4, count * 4 + i * 60);
            var entry = 56 + count * 4 + i * 60;
            Write(bytes, entry, type);
            BinaryPrimitives.WriteSingleLittleEndian(bytes.AsSpan(entry + 12), 1.5f);
            BinaryPrimitives.WriteSingleLittleEndian(bytes.AsSpan(entry + 16), 2);
            BinaryPrimitives.WriteSingleLittleEndian(bytes.AsSpan(entry + 20), 3);
            foreach (var offset in new[] { 36, 40, 44 }) BinaryPrimitives.WriteSingleLittleEndian(bytes.AsSpan(entry + offset), 1);
            Write(bytes, entry + 48, type == 57 ? 2 : 987);
            if (type == 57) bytes[entry + 54] = 1;
        }
        return bytes;
    }
    private static void Write(byte[] bytes, int offset, int value) => BinaryPrimitives.WriteInt32LittleEndian(bytes.AsSpan(offset), value);
