    private static CaptureResult Capture(Inspector inspector, DomainPayload payload, ToolOptions? options = null)
    {
        using var engine = new DiagnosticEngine(new Source { Read = (_, _, _, _) => new(payload) }, new FakeClock());
        Equal(QueueStatus.Accepted, engine.EnqueueTool(inspector, options ?? Options(inspector)));
        engine.Tick(); return engine.View().Results[^1];
    }
    private static void Drain(DiagnosticEngine engine)
    {
        for (var i = 0; i < 150; i++)
        {
            engine.Tick();
            if (engine.View() is { ActiveRequest: null, Pending: 0 }) return;
        }
        throw new Exception("Domain job failed to terminate");
    }
