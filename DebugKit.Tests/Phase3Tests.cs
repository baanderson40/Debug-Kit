    private static void ShorteningExports()
    {
        var result = Capture(Inspector.FamiliarData, Payload(Inspector.FamiliarData, Row(value: new string('x', 200))));
        Equal(0, result.Omitted); Check(!result.Partial);
        var text = ReportCodec.Describe(result, 0);
        Check(text.Contains("Text-shortened fields 1") && text.Contains("[text shortened; source 200 UTF-16 units]"));
        var view = new EngineView(0, 0, null, 0, [result], 0, 0, 0, true);
        var preview = ReportCodec.Create(view, Provenance.Create("0.3.2.0", "15.0.3.9"), ReportFormat.Json, DateTimeOffset.UtcNow);
        using (var json = JsonDocument.Parse(preview.Content))
        {
            var field = json.RootElement.GetProperty("Results")[0].GetProperty("Payload").GetProperty("Rows")[0].GetProperty("Fields")[0];
            Check(field.GetProperty("TextShortened").GetBoolean()); Equal(200, field.GetProperty("OriginalTextLength").GetInt32());
        }
        var textPreview = ReportCodec.Create(view, Provenance.Create("0.3.2.0", "15.0.3.9"), ReportFormat.Text, DateTimeOffset.UtcNow);
        Check(textPreview.Content.Contains("[text shortened; source 200 UTF-16 units]"));
        var directory = Path.Combine(Path.GetTempPath(), "debugkit-cleanup-" + Guid.NewGuid().ToString("N"));
        try
        {
            using var exporter = new ReportExporter(directory);
            foreach (var frozen in new[] { preview, textPreview })
            {
                Equal(ExportStatus.Success, exporter.ExportAsync(frozen).GetAwaiter().GetResult());
                Check(File.ReadAllBytes(Path.Combine(directory, frozen.FileName)).AsSpan().SequenceEqual(frozen.Bytes.AsSpan()));
                File.Delete(Path.Combine(directory, frozen.FileName));
            }
        }
        finally { if (Directory.Exists(directory) && !Directory.EnumerateFileSystemEntries(directory).Any()) Directory.Delete(directory); }
    }
